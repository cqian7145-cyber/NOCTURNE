import { expect, test } from '@playwright/test';

test('domain, measured progress, keyboard commands and chronicle work across reloads', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.setFixedTime(new Date('2026-11-23T02:00:00Z'));
  await page.goto('/');
  const nav = page.getByRole('navigation', { name: '主导航' });
  await nav.getByRole('link', { name: '人生领域' }).click();
  await page.getByRole('button', { name: '新建领域' }).click();
  await page.getByLabel('名称', { exact: true }).fill('智识');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('heading', { name: '智识', exact: true })).toBeVisible();
  await page.keyboard.press('Control+k');
  const search = page.getByLabel('搜索操作、习惯或目标');
  await expect(search).toBeFocused();
  await search.fill('新建习惯');
  await search.press('Enter');
  const form = page.getByRole('dialog', { name: '创建习惯' });
  await form.getByLabel('习惯名称').fill('细读文章');
  await form.getByLabel('人生领域').selectOption({ label: '智识' });
  await form.getByLabel('按数量打卡').check();
  await form.getByRole('button', { name: '保存习惯' }).click();
  await expect(form).toBeHidden();
  await nav.getByRole('link', { name: '今日总览', exact: true }).click();
  await page.getByRole('button', { name: '完成打卡 细读文章' }).click();
  await page.getByLabel('实际数量（分钟）').fill('4');
  await page.getByRole('button', { name: '保存记录' }).click();
  await expect(page.getByText('部分完成 · 4 分钟')).toBeVisible();
  await page.reload();
  await expect(page.getByText('部分完成 · 4 分钟')).toBeVisible();
  await page.keyboard.press('Control+k');
  await search.fill('打卡 细读文章');
  await search.press('Enter');
  await page.getByLabel('实际数量（分钟）').fill('15');
  await page.getByRole('button', { name: '保存记录' }).click();
  await expect(page.locator('.ring-caption')).toHaveText('100%');
  await page.screenshot({ path: info.outputPath('ascension-desktop.png'), fullPage: true });
  await nav.getByRole('link', { name: '成长编年史' }).click();
  await expect(page.getByText('细读文章 · 第 1 次达标')).toBeVisible();
  await page.getByRole('button', { name: '记录事件' }).click();
  await page.getByLabel('事件标题').fill('完成首次读书分享');
  await page.getByRole('button', { name: '保存事件' }).click();
  await expect(page.getByRole('heading', { name: '完成首次读书分享' })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 812 });
  await expect(page.getByRole('navigation', { name: '移动导航' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375);
  await expect(page.getByRole('heading', { name: '成长编年史' })).toBeVisible();
  await expect(page.locator('.route')).toHaveCSS('opacity', '1');
  await page.screenshot({ path: info.outputPath('ascension-mobile.png'), fullPage: true });
});

test('production manifest is installable and a lazy route opens offline', async ({ context, page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Make today count.' })).toBeVisible();
  const cdp = await context.newCDPSession(page);
  const result = await cdp.send('Page.getAppManifest');
  expect(result.errors).toEqual([]);
  expect(JSON.parse(result.data!).display).toBe('standalone');
  expect(JSON.parse(result.data!).icons.map((icon: { sizes: string }) => icon.sizes)).toEqual(['192x192', '512x512']);
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true);
  await context.setOffline(true);
  await page.goto('/#/chronicle');
  await expect(page.getByRole('heading', { name: '成长编年史' })).toBeVisible();
});
